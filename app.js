// normalize
function norm(s){ return String(s || "").trim().toUpperCase(); }

// compose description: if user provided action, prefix it with "AÇÃO - " and then the base description
function composeDescription(entry){
  const base = entry.description || "";
  const action = (actionInput && actionInput.value || "").trim();
  let composed = "";
  if(action){
    composed = `AÇÃO - ${action}\n\n${base}`;
  } else {
    composed = base;
  }

  // append format/quantity suffix if selected
  const fmt = currentFormat || "";
  const qty = (qtySelect && qtySelect.value) ? qtySelect.value.trim() : "";
  if(qty || fmt){
    // default display for qty is prefixed with x, for format show 'formato'
    const qtyText = qty ? `x${qty}` : "";
    const fmtText = fmt ? `formato${fmt}` : "";
    // ensure a space between parts and prefix with newline
    composed = `${composed}\n\n${[qtyText, fmtText].filter(Boolean).join(' ')}`;
  }

  return composed;
}

function hideSearchRows(){
  searchRows.forEach(r => r.classList.add('hidden'));
  if(actionRow) actionRow.classList.add('hidden');
}
function showSearchRows(){
  searchRows.forEach(r => r.classList.remove('hidden'));
  if(actionRow) actionRow.classList.remove('hidden');
}

function showResult(entry){
  titleEl.textContent = entry.title;
  descEl.textContent = composeDescription(entry);

  // clear any previous hint/error
  if(hintEl){
    hintEl.textContent = "Sistema de Busca de Prompt";
    hintEl.classList.remove('error');
  }

  // ensure path is URI-encoded (handles spaces/accents) and provide a safe fallback
  try {
    // Request image with anonymous CORS so we can draw to canvas as a fallback if fetch fails
    imgEl.crossOrigin = 'anonymous';
    imgEl.src = encodeURI(entry.image || '/modelsheet.jpg');
  } catch (e) {
    imgEl.crossOrigin = 'anonymous';
    imgEl.src = '/modelsheet.jpg';
  }
  imgEl.alt = entry.title;

  // if image fails to load, use the modelsheet fallback (guaranteed asset)
  imgEl.onerror = () => {
    if (!imgEl.src.endsWith('/modelsheet.jpg')) {
      imgEl.crossOrigin = 'anonymous';
      imgEl.src = '/modelsheet.jpg';
      imgEl.alt = entry.title + ' (imagem não disponível)';
    }
  };

  // hide the search inputs while showing the result
  hideSearchRows();
  resultEl.classList.remove('hidden');
}

// search handler
function search(){
  const key = norm(qInput.value);
  if(!key) return;
  const entry = DATA[key];
  if(entry){
    showResult(entry);
  } else {
    // show a concise inline error in the hint area and keep the search inputs visible
    const rawQuery = (qInput && qInput.value) ? qInput.value.trim() : "";
    if(hintEl){
      hintEl.textContent = "Nome não cadastrado.";
      hintEl.classList.add('error');
    }
    // ensure result panel is hidden
    resultEl.classList.add('hidden');
    // keep inputs visible so the user can correct the query
    showSearchRows();
    // small visual feedback: briefly flash the search box border
    qInput.classList.add('error-flash');
    setTimeout(()=> qInput.classList.remove('error-flash'), 700);
  }
}

// reset search to allow a new search after copy
function resetSearch(){
  qInput.value = "";
  if(actionInput) actionInput.value = "";
  // reset custom format control UI/state
  updateFormatUI("");
  if(qtySelect) qtySelect.value = "4";
  qInput.focus();
  // show search inputs again and clear result
  showSearchRows();
  resultEl.classList.add('hidden');
  titleEl.textContent = "";
  descEl.textContent = "";
  imgEl.src = "";
  imgEl.alt = "";
  // clear hint/error
  if(hintEl){
    hintEl.textContent = "Sistema de Busca de Prompt";
    hintEl.classList.remove('error');
  }
}

/* copy text-only */
async function copyTextOnly(){
  const title = titleEl.textContent || "";
  const text = title + "\n\n" + descEl.textContent;
  try{
    await navigator.clipboard.writeText(text);
    flashButton(btnCopyText, "Copiado");
    // do NOT reset the search automatically; user will press "Sair" to close
  }catch(e){
    console.error("copyTextOnly failed", e);
    flashButton(btnCopyText, "Erro");
  }
}

